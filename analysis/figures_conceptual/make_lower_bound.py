"""Generate fig_lower_bound.svg: energy-vs-time view of the per-EV bounds l_i, u_i (safety_layer.md S 3).

Purely conceptual axes (no numbers shown). Internal toy model used to place the curves consistently:
  energy units: E_min = 10, E_req = 55, E_cap = 60; one step = 1 time unit
  phi(E) = E + min(6, 0.35 (E_cap - E))  (nominal 6 per step, linear taper above E = 42.86; A1 holds)
  thresholds B(k) (S8): 55, 52.31, 48.17, 42.17, 36.17, 30.17, 24.17, 18.17, 12.17, 10, 10, ...
  arrival t_arr = 1, last controlled step d = 12, departure energy at d+1 = 13
  latest-start curve: points (d+1-k, B(k))
  history E(1..7) = 18, 24, 28, 25, 21, 22, 27  (each step within [-6, +6], always >= B(d-s+1))
  now t = 7: tau = d - t + 1 = 6, B(tau) = 24.17 <= E = 27 (individually feasible)
    l*dt = B(tau-1) - E = 30.17 - 27 = 3.17 ; u*dt = phi(27) - 27 = 6 ; p_min*dt = -min(6, 27 - 10) = -6
  upper envelope from now: Psi_k(27) = 33, 39, 45, 50.25, 53.66, 55.88 (t = 8..13) >= E_req at d+1
"""
from __future__ import annotations

from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
Emin, Ereq, Ecap = 10.0, 55.0, 60.0
d, tarr, tnow = 12, 1, 7
RATE = 0.35                     # taper slope: phi(E) = E + min(6, RATE (E_cap - E))


def phi(E):
    return E + min(6.0, RATE * (Ecap - E))


def B(k):
    """Backward-reachable threshold (S8) by bisection (phi continuous, non-decreasing: A1)."""
    b = Ereq
    for _ in range(k):
        if phi(Emin) >= b:
            b = Emin
            continue
        lo, hi = Emin, b
        for _ in range(100):
            mid = 0.5 * (lo + hi)
            lo, hi = (lo, mid) if phi(mid) >= b else (mid, hi)
        b = hi
    return b


Bs = [B(k) for k in range(13)]
hist = {1: 18, 2: 24, 3: 28, 4: 25, 5: 21, 6: 22, 7: 27}
for s_, e in hist.items():
    assert e >= B(d - s_ + 1) - 1e-9, (s_, e)
for a, b in zip(list(hist.values())[:-1], list(hist.values())[1:]):
    assert -6 <= b - a <= phi(a) - a + 1e-9
E = hist[tnow]
tau = d - tnow + 1
l_dt, u_dt, pmin_dt = B(tau - 1) - E, phi(E) - E, -min(6, E - Emin)
assert 0 < l_dt < u_dt and B(tau) <= E
env = [E]
for _ in range(d + 1 - tnow):
    env.append(phi(env[-1]))
assert env[-1] >= Ereq
print("B(k) =", [round(b, 2) for b in Bs], " l*dt =", round(l_dt, 2), " u*dt =", u_dt, " pmin*dt =", pmin_dt,
      " envelope =", [round(v, 2) for v in env])

