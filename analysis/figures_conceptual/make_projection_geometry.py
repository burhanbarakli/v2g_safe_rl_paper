"""Generate fig_projection_geometry.svg (2-EV illustration of the safety-layer projection).

Concrete example (kW):
  box     l = (-5, -3), u = (6, 5)
  slab    -C_rev = -4 <= p1 + p2 <= C_tilde = 6
  raw     x = (12, 3)                         (outside box and slab)
  clip(x, l, u)            = (6, 3)           sum 9 > C_tilde -> infeasible
  lambda* (root of S(lambda) = C_tilde) = 3
  shifted x - lambda*1     = (9, 0)
  p* = clip(x - lambda*1, l, u) = (6, 0)      sum 6 = C_tilde
The script checks p* against method/projection_ref.project and against a brute-force minimisation of
||p - x|| over a fine grid of the feasible set, then writes the SVG with these exact coordinates.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
REF = HERE.parents[1] / "method"            # project-root method/projection_ref.py (test oracle)

l = np.array([-5.0, -3.0])
u = np.array([6.0, 5.0])
Ct, Crev = 6.0, 4.0
x = np.array([12.0, 3.0])


def S(lam):
    return np.clip(x - lam, l, u).sum()


def solve():
    lo, hi = 0.0, 100.0
    for _ in range(200):
        mid = 0.5 * (lo + hi)
        (lo, hi) = (mid, hi) if S(mid) > Ct else (lo, mid)
    lam = hi
    return lam, x - lam, np.clip(x - lam, l, u)


lam, shifted, p = solve()
clipx = np.clip(x, l, u)
assert abs(lam - 3) < 1e-9 and np.allclose(shifted, [9, 0]) and np.allclose(p, [6, 0]) and np.allclose(clipx, [6, 3])

# check 1: reference implementation of the method
if (REF / "projection_ref.py").exists():
    sys.path.insert(0, str(REF))
    import projection_ref as pr
    out = pr.project(x[None, :] / 1.0, l[None, :], u[None, :], np.array([Ct]), np.array([Crev]))
    pref = np.asarray(out[0] if isinstance(out, tuple) else out).reshape(-1)[:2]
    assert np.allclose(pref, p, atol=1e-9), (pref, p)
    print("projection_ref.project agrees:", pref)
# check 2: brute force over the feasible set
g1, g2 = np.meshgrid(np.linspace(l[0], u[0], 1101), np.linspace(l[1], u[1], 801))
ok = (g1 + g2 <= Ct + 1e-12) & (g1 + g2 >= -Crev - 1e-12)
d = np.where(ok, (g1 - x[0]) ** 2 + (g2 - x[1]) ** 2, np.inf)
k = np.unravel_index(np.argmin(d), d.shape)
assert abs(g1[k] - p[0]) < 0.02 and abs(g2[k] - p[1]) < 0.02, (g1[k], g2[k])
print(f"lambda* = {lam:.6f}, shifted = {shifted}, p* = {p}, clip(x) = {clipx}, brute force = ({g1[k]:.3f}, {g2[k]:.3f})")

# ---------------------------------------------------------------- drawing
s = 30.0                          # px per kW
P1 = (-7.5, 14.0)
P2 = (-6.0, 7.2)
ox, oy = 70.0, 20.0               # top-left margin
W = ox + (P1[1] - P1[0]) * s + 30
H = oy + (P2[1] - P2[0]) * s + 14 + 3.0 * s + 12


def X(a):
    return ox + (a - P1[0]) * s


def Y(b):
    return oy + (P2[1] - b) * s


def pt(v):
    return f"{X(v[0]):.1f},{Y(v[1]):.1f}"


def clip_poly(poly, a, b, c):
    """Keep a*p1 + b*p2 <= c (Sutherland-Hodgman)."""
    out = []
    for i in range(len(poly)):
        P, Q = poly[i], poly[(i + 1) % len(poly)]
        fp, fq = a * P[0] + b * P[1] - c, a * Q[0] + b * Q[1] - c
        if fp <= 0:
            out.append(P)
        if fp * fq < 0:
            t = fp / (fp - fq)
            out.append((P[0] + t * (Q[0] - P[0]), P[1] + t * (Q[1] - P[1])))
    return out


box = [(l[0], l[1]), (u[0], l[1]), (u[0], u[1]), (l[0], u[1])]
K = clip_poly(clip_poly(box, 1, 1, Ct), -1, -1, Crev)
Kpts = " ".join(pt(v) for v in K)


def line_sum(c):
    # p1 + p2 = c within the plot window
    pts = []
    for a in P1:
        b = c - a
        if P2[0] <= b <= P2[1]:
            pts.append((a, b))
    for b in P2:
        a = c - b
        if P1[0] <= a <= P1[1]:
            pts.append((a, b))
    pts = sorted(set(pts))
    return pts[0], pts[-1]


cu0, cu1 = line_sum(Ct)
cl0, cl1 = line_sum(-Crev)


def hatch(c, side, n=16):
    """Short ticks on the infeasible side of p1+p2=c (side=+1: above)."""
    a0, a1 = line_sum(c)
    out = []
    for i in range(1, n):
        t = i / n
        q = (a0[0] + t * (a1[0] - a0[0]), a0[1] + t * (a1[1] - a0[1]))
        e = (q[0] + side * 0.32, q[1] + side * 0.32)
        out.append(f'<line class="hat" x1="{X(q[0]):.1f}" y1="{Y(q[1]):.1f}" x2="{X(e[0]):.1f}" y2="{Y(e[1]):.1f}"/>')
    return "\n  ".join(out)


