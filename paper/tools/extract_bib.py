#!/usr/bin/env python3
"""Write manuscript/refs.bib with only the entries cited in manuscript/sections/*.tex.

Usage: python3 tools/extract_bib.py [--src ../lit/merged/references.bib]

- Keys are collected from \\cite{...} commands in the section files.
- Entries are copied from the verified project bibliography (never edited by hand there).
- For pdflatex/BibTeX robustness, the copy is normalised: non-ASCII characters are
  replaced by LaTeX commands, month names by BibTeX macros, and @inbook entries
  that carry a booktitle become @incollection (chapter in an edited volume).
- Exits with an error if a cited key is missing from the source bibliography.
"""
import argparse, glob, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
DEFAULT_SRC = os.path.join(os.path.dirname(REPO), "lit", "merged", "references.bib")

UNI = {
    "\u2010": "-", "\u2011": "-", "\u2013": "--", "\u2014": "---", "\u2019": "'", "\u2018": "`",
    "\u00a0": " ", "\u00ae": "\\textregistered{}", "\u0131": "{\\i}", "\u0141": "{\\L}",
    "\u00f8": "{\\o}", "\u00e1": "{\\'a}", "\u00e4": "{\\\"a}", "\u00e8": "{\\`e}", "\u00e9": "{\\'e}",
    "\u00ed": "{\\'\\i}", "\u00f3": "{\\'o}", "\u00f6": "{\\\"o}", "\u00fc": "{\\\"u}", "\u0103": "{\\u{a}}",
    "\u201c": "``", "\u201d": "''",
}
MONTHS = {m.lower(): m[:3].lower() for m in ["January", "February", "March", "April", "May", "June", "July",
                                              "August", "September", "October", "November", "December"]}
MONTHS.update({"sept": "sep"})


def entries(text):
    """Yield (key, raw_entry) using brace matching."""
    for m in re.finditer(r"@(\w+)\s*\{\s*([^,\s]+)\s*,", text):
        start, depth, i = m.start(), 0, m.end() - 1
        j = text.index("{", m.start())
        for k in range(j, len(text)):
            if text[k] == "{":
                depth += 1
            elif text[k] == "}":
                depth -= 1
                if depth == 0:
                    yield m.group(2), text[start:k + 1]
                    break


def normalise(e):
    for a, b in UNI.items():
        e = e.replace(a, b)
    e = e.replace("&amp;", "&")
    e = re.sub(r"(?<!\\)&", r"\\&", e)
    e = re.sub(r"month\s*=\s*\{?([A-Za-z]+)\}?", lambda m: "month=" + MONTHS.get(m.group(1).lower(), "{" + m.group(1) + "}"), e)
    if e.lower().startswith("@inbook") and "booktitle" in e:
        e = "@incollection" + e[len("@inbook"):]
    if e.lower().startswith("@article") and not re.search(r"\bjournal\s*=", e):
        e = "@misc" + e[len("@article"):]
        if "ssrn" in e.lower():
            e = e.rstrip()[:-1].rstrip().rstrip(",") + ", note={SSRN preprint} }"
    m = re.search(r"eprint\s*=\s*\{([^}]*)\}", e)
    if m and "arxiv" in e.lower() and not re.search(r"\bnote\s*=", e):
        e = e.rstrip()[:-1].rstrip().rstrip(",") + ",\n  note = {arXiv preprint arXiv:" + m.group(1) + "}\n}"
    bad = sorted(set(c for c in e if ord(c) > 127))
    if bad:
        print("WARNING: remaining non-ASCII characters:", bad, file=sys.stderr)
    return e


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=DEFAULT_SRC)
    ap.add_argument("--sections", nargs="+", default=[os.path.join(REPO, "manuscript", "sections"),
                                                      os.path.join(REPO, "supplementary", "sections")])
    ap.add_argument("--out", default=os.path.join(REPO, "manuscript", "refs.bib"))
    a = ap.parse_args()
    cited = []
    files = [f for d in a.sections for f in sorted(glob.glob(os.path.join(d, "*.tex")))]
    for f in files:
        t = re.sub(r"(?<!\\)%.*", "", open(f, encoding="utf-8").read())
        for m in re.finditer(r"\\cite\{([^}]*)\}", t):
            for k in m.group(1).split(","):
                k = k.strip()
                if k and k not in cited:
                    cited.append(k)
    src = dict(entries(open(a.src, encoding="utf-8").read()))
    missing = [k for k in cited if k not in src]
    if missing:
        sys.exit("ERROR: cited keys not in source bibliography: " + ", ".join(missing))
    with open(a.out, "w", encoding="utf-8") as fh:
        fh.write("% Generated by tools/extract_bib.py from the verified project bibliography.\n")
        fh.write("% Do not edit by hand; edit lit/merged/references.bib and re-run the script.\n\n")
        for k in cited:
            fh.write(normalise(src[k]) + "\n\n")
    print(f"{len(cited)} cited keys written to {a.out}")


if __name__ == "__main__":
    main()
