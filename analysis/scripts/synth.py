"""Synthetic result generator - FOR TESTING THE PIPELINE ONLY.

Writes a results/raw-like tree that follows code_spec.md §2-§3 exactly, with random values.
Method effects (gap levels, scaling slopes, violation rates) are random draws, NOT a model of
expected results; nothing generated here may be reported or used to anticipate results.
The tree carries the sentinel file SYNTHETIC_DATA and `"synthetic": true` in every meta.json;
the pipeline then watermarks every output and refuses to write outside synthetic_test/.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd

from load import EPISODE_COLS, ORACLE_EXTRA, ORACLE_CEIL, ORACLE_PEN, PEN_COL, TRAIN_COLS, SYNTH_SENTINEL
from common import TEST_SIZES

PROFILES = ["workplace", "public", "private"]
RHOS = [4, 7]
LEARNED = ["attn_safe", "attn_penalty", "mlp_safe", "mlp_penalty", "attn_lagrangian", "attn_proj_nolb",
           "deepsets_safe", "attn_penalty_w1", "attn_penalty_w100", "attn_safe_dt5", "attn_safe_trainN50",
           "attn_safe_beta0", "attn_safe_curriculum", "attn_safe_small", "attn_penalty_dense",
           "attn_safe_conf_a0.01", "attn_safe_conf_a0.05", "attn_safe_conf_a0.1", "attn_safe_conf_a0.2",
           "attn_safe_conf_point"]
HEUR = ["afap", "afap_safe", "alap", "alap_safe", "rr", "rr_safe", "llf", "llf_safe", "sllf", "sllf_safe",
        "price_llf", "price_llf_safe"]
MPC = ["empc", "empc_safe", "empc_highs", "empc_highs_safe", "empc_highs_24h", "empc_highs_24h_safe"]
EVAL_ONLY = {"attn_safe_noadm": "attn_safe", "attn_penalty_noadm": "attn_penalty",
             "attn_penalty_safedeploy": "attn_penalty", "evgnn": None, "evgnn_safe": None}
SENS_TAGS = {"soc0.8": "public", "dt5": "private", "thr0.05": "workplace", "dpf0.9": "public"}


def _runs_on(m, c):
    """Which (method, configuration) pairs exist (mirrors the real run plan)."""
    fam = c.get("family", "grid")
    if m in ("empc", "empc_safe"):
        return fam == "literature"
    if m == "attn_safe_trainN50":
        return fam == "grid" and c["N"] >= 50
    if m == "attn_safe_dt5":
        return c.get("tag") == "dt5"
    if m in ("mlp_safe", "mlp_penalty"):
        return c["N"] <= 20                      # DD43(3)
    if m in ("attn_penalty_w1", "attn_penalty_w100"):
        return fam == "grid" and c["N"] == 20 and c["rho_tr"] == 4.0
    if fam == "sensitivity" and c.get("tag") == "dt5":
        return m in ("attn_safe_dt5", "llf_safe", "empc_highs_safe", "afap_safe")
    return True


def _h8(*a) -> str:
    return hashlib.sha1("|".join(map(str, a)).encode()).hexdigest()[:8]


def configs(small=False):
    sizes = [5, 10, 20, 50] if small else TEST_SIZES
    out = [dict(test_cfg_id=f"{p}_N{n}_rho{r}", profile=p, N=n, rho_tr=float(r))
           for p in PROFILES for n in sizes for r in RHOS]
    out.append(dict(test_cfg_id="literature_N25", profile="workplace", N=25, rho_tr=4.0, family="literature"))
    for tag, prof in SENS_TAGS.items():
        out.append(dict(test_cfg_id=f"{prof}_N20_rho4_{tag}", profile=prof, N=20, rho_tr=4.0, family="sensitivity", tag=tag))
    for p in PROFILES:                                                    # DD36 stress level
        for n in ([20] if small else [20, 200]):
            out.append(dict(test_cfg_id=f"{p}_N{n}_rho3", profile=p, N=n, rho_tr=3.0, family="stress"))
    return out


def _safe(m):
    import names
    return names.info(m).safety_layer


def generate(out_raw: str | Path, seed: int = 0, replay_scale: float = 1.0, n_seeds: int = 5,
             small: bool = False, with_smoke: bool = True) -> Path:
    out = Path(out_raw)
    out.mkdir(parents=True, exist_ok=True)
    (out / SYNTH_SENTINEL).write_text("SYNTHETIC TEST DATA - NOT RESULTS. Generated by analysis/scripts/synth.py.\n")
    rng = np.random.default_rng(seed)
    cfgs = configs(small)
    nrep = {c["test_cfg_id"]: max(4, int(round((100 if c["N"] <= 50 else 50) * replay_scale))) for c in cfgs}

    # ---- oracle (random, positive profits of random size) ----
    oracle = {}
    for c in cfgs:
        k = nrep[c["test_cfg_id"]]
        o = c["N"] * rng.normal(3.0, 1.2, k) + rng.normal(0, 2, k)
        oracle[c["test_cfg_id"]] = o
        df = _episode_frame(c, "oracle", 0, "", f"oracle__{c['test_cfg_id']}", o, rng, safe=True, oracle=True)
        df["solve_time_s"] = rng.uniform(0.5, 10, k)
        df["solver_status"] = "Optimal"
        df[ORACLE_CEIL] = o + rng.uniform(0, 0.05, k)
        df[ORACLE_PEN] = o + rng.uniform(0, 0.08, k)
        df[PEN_COL] = df["profit_eur"]
        df["shortfall_stage_kwh"] = 0.0
        d = out / f"oracle__{c['test_cfg_id']}"
        d.mkdir(exist_ok=True)
        df[EPISODE_COLS + [PEN_COL, ORACLE_CEIL, ORACLE_PEN] + ORACLE_EXTRA].to_csv(d / "episodes.csv", index=False)
        _meta(d, rng)

    methods = LEARNED + HEUR + MPC + list(EVAL_ONLY)
    effect = {m: dict(g0=rng.uniform(1, 35), slope=rng.uniform(-4, 6), sd_seed=rng.uniform(0.3, 3),
                      sd_ep=rng.uniform(1, 6)) for m in methods}
    for m in methods:
        learned = m in LEARNED or m in EVAL_ONLY
        seeds = range(min(3, n_seeds)) if m == "attn_safe_trainN50" else (range(n_seeds) if learned else [0])
        for s in seeds:
            exp_id = f"{m}__{'trainmix' if learned else 'testgrid'}__s{s}__{_h8(m, s)}"
            parts = []
            seed_off = rng.normal(0, effect[m]["sd_seed"])
            for c in cfgs:
                if not _runs_on(m, c):
                    continue
                o = oracle[c["test_cfg_id"]]
                g = (effect[m]["g0"] + seed_off + effect[m]["slope"] * np.log2(c["N"] / 10)
                     + rng.normal(0, effect[m]["sd_ep"], o.size))
                prof = o - g / 100 * np.abs(o)
                parts.append(_episode_frame(c, m, s, "20" if learned else "", exp_id, prof, rng, safe=_safe(m)))
            if not parts:
                continue
            df = pd.concat(parts, ignore_index=True)
            df[PEN_COL] = df["profit_eur"] - 10 * df["energy_not_served_kwh"] - 10 * df["tr_violation_kwh"]
            if m.startswith("evgnn"):
                df["in_distribution"] = (df["N"] == 20) & (df["rho_tr"] == 4.0)
            elif learned:
                df["in_distribution"] = df["N"].isin([10, 20]) & df["rho_tr"].isin([4.0, 7.0])
            if m.startswith("attn_safe_conf_"):
                a = float(m.split("_a")[-1]) if "_a" in m else np.nan
                cov = np.clip((1 - a if np.isfinite(a) else 0.5) + rng.normal(0, 0.02, len(df)), 0, 1)
                df["alpha"] = a
                df["conformal_coverage"] = cov
                df["n_evs_departed_before_bound"] = np.round((1 - cov) * df["n_evs"]).astype(int)
                df["coverage_frac"] = cov
                df["mean_d_minus_dlo"] = rng.uniform(1, 12, len(df))
            d = out / exp_id
            d.mkdir(exist_ok=True)
            cols = EPISODE_COLS + [c for c in ("n_steps", "n_evs_stay_infeasible", "share_evs_stay_feasible",
                                               "agg_upper_active_steps", "agg_lower_active_steps", "lb_active_frac",
                                               "n_evs_unserved_shared", "energy_not_served_shared_kwh")] + \
                [c for c in (PEN_COL, "alpha", "conformal_coverage", "n_evs_departed_before_bound",
                                               "coverage_frac", "mean_d_minus_dlo", "in_distribution") if c in df]
            df[cols].to_csv(d / "episodes.csv", index=False)
            _meta(d, rng, learned=learned)
            if m in LEARNED and not m.startswith("attn_safe_conf_"):
                _train_log(d, exp_id, rng)
            if m in ("attn_safe", "attn_penalty") and s == 0:
                _steps(d, exp_id, rng, safe=_safe(m))

    if with_smoke:   # must be dropped by the loader
        d = out / f"attn_safe__smoke__s0__{_h8('smoke')}"
        d.mkdir(exist_ok=True)
        c = cfgs[0]
        df = _episode_frame(c, "attn_safe", 0, "10", d.name, np.full(3, 1e6), rng, safe=True)
        df["smoke"] = True
        df[EPISODE_COLS].to_csv(d / "episodes.csv", index=False)
        (d / "meta.json").write_text(json.dumps({"smoke": True, "synthetic": True}))
    return out


def _episode_frame(c, method, seed, train_n, exp_id, profit, rng, safe, oracle=False):
    k = profit.size
    N = c["N"]
    n_evs = rng.poisson(0.8 * N, k) + 1
    infeas = rng.poisson(max(0.05, 6 / np.sqrt(N)), k)
    if safe:
        unserved = rng.binomial(n_evs, 0.004 if not oracle else 0.0)
        viol_steps = np.zeros(k, int)
        fb1 = infeas.copy() if not oracle else np.zeros(k, int)
    else:
        unserved = rng.binomial(n_evs, rng.uniform(0.01, 0.15))
        viol_steps = rng.poisson(rng.uniform(0.5, 8), k)
        fb1 = np.zeros(k, int)
    ens = unserved * rng.exponential(2.0, k)
    viol_kwh = viol_steps * rng.exponential(0.6, k) * N / 10
    df = pd.DataFrame(dict(
        exp_id=exp_id, method=method, seed=seed, train_N=train_n, test_cfg_id=c["test_cfg_id"],
        profile=c["profile"], N=N, rho_tr=c["rho_tr"], dt_min=15, replay_id=np.arange(k),
        profit_eur=profit, energy_charged_kwh=n_evs * rng.uniform(8, 20, k),
        energy_discharged_kwh=n_evs * rng.uniform(0, 5, k), n_evs=n_evs,
        n_evs_capped=rng.binomial(n_evs, 0.05), n_evs_admission_reduced=rng.binomial(n_evs, 0.02) if safe else 0,
        n_evs_unserved=unserved, energy_not_served_kwh=ens, frac_evs_unserved=unserved / n_evs,
        user_satisfaction_mean=np.clip(1 - unserved / n_evs * rng.uniform(0, 0.5, k), 0, 1),
        tr_violation_steps=viol_steps, tr_violation_kwh=viol_kwh,
        tr_violation_max_kw=np.where(viol_steps > 0, rng.exponential(5, k), 0.0),
        infeasible_steps=infeas, fb0_steps=0, fb1_steps=fb1, fb2_steps=0, fb1star_steps=0,
        a5_deficit_kwh=np.where(infeas > 0, rng.exponential(0.3, k), 0.0) if safe else 0.0,
        proj_dist_mean=rng.uniform(0, 2, k) if (safe and not oracle) else np.nan,
        inference_ms_per_step_mean=0 if oracle else rng.uniform(0.2, 0.4) * N ** rng.uniform(0.3, 1.0) * rng.lognormal(0, 0.05, k),
        oracle_profit_eur=np.nan, smoke=False))
    df["inference_ms_per_step_p95"] = df["inference_ms_per_step_mean"] * 1.3
    # DD43 columns
    T = 112
    stay_inf = np.minimum(n_evs, rng.binomial(n_evs, np.clip(infeas / T * 4, 0, 1)))
    df["n_steps"] = T
    df["n_evs_stay_infeasible"] = stay_inf
    df["share_evs_stay_feasible"] = 1 - stay_inf / n_evs
    df["agg_upper_active_steps"] = rng.binomial(T, rng.uniform(0.05, 0.4), k)
    df["agg_lower_active_steps"] = rng.binomial(T, rng.uniform(0.0, 0.05), k)
    df["lb_active_frac"] = rng.uniform(0.0, 0.3, k) if safe else rng.uniform(0, 0.05, k)
    df["n_evs_unserved_shared"] = unserved
    df["energy_not_served_shared_kwh"] = ens
    return df


def _meta(d, rng, learned=False):
    (d / "meta.json").write_text(json.dumps(dict(
        synthetic=True, smoke=False, git_hash="SYNTHETIC", ev2gym_commit="55ef368c25a58476a9eeaed5111f112a63a38ca8",
        hostname="synthetic", device="cpu", wall_clock_s=float(rng.uniform(5000, 12000) if learned else rng.uniform(100, 900)),
        train_wall_clock_s=float(rng.uniform(5000, 12000)) if learned else None), indent=1))


def _train_log(d, exp_id, rng):
    steps = np.arange(0, 3_000_001, 20_480)
    k = steps.size
    target, rate = rng.uniform(20, 80), rng.uniform(2, 8) / 3e6
    ret = target * (1 - np.exp(-rate * steps)) - 30 + rng.normal(0, 3, k)
    pd.DataFrame(dict(
        exp_id=exp_id, env_steps=steps, wall_clock_s=steps / 3e6 * rng.uniform(6000, 11000),
        episode_return_eur_mean=ret, episode_return_eur_std=rng.uniform(5, 15, k),
        frac_unserved_mean=np.abs(rng.normal(0.05, 0.02, k)) * np.exp(-steps / 1e6),
        tr_violation_kwh_mean=np.abs(rng.normal(2, 1, k)) * np.exp(-steps / 1.5e6),
        policy_loss=rng.normal(0, 0.01, k), value_loss=np.abs(rng.normal(0.5, 0.2, k)),
        entropy=np.linspace(1.5, 0.3, k), approx_kl=np.abs(rng.normal(0.01, 0.003, k)),
        clip_frac=rng.uniform(0.05, 0.2, k), beta_reg=rng.uniform(0, 0.1, k),
        proj_dist_mean=rng.uniform(0, 2, k), lr=np.linspace(3e-4, 0, k)))[TRAIN_COLS].to_csv(d / "train_log.csv", index=False)


def _steps(d, exp_id, rng, safe):
    T = 112
    t = np.arange(T)
    hour = (5 + t * 0.25) % 24
    price = 0.15 + 0.1 * np.sin((hour - 6) / 24 * 2 * np.pi) + rng.normal(0, 0.02, T)
    N, rho = 20, 4.0
    Ptr = np.full(T, rho * N)
    Pinf = 0.4 * Ptr * (0.5 + 0.5 * np.sin((hour - 9) / 24 * 2 * np.pi) ** 2)
    Ppv = np.clip(0.38 * Ptr * np.sin((hour - 6) / 12 * np.pi), 0, None)
    C, Crev = Ptr - Pinf + Ppv, Ptr + Pinf - Ppv
    occ = np.clip(np.round(N * 0.6 * np.exp(-((hour - 12) / 4) ** 2)), 0, N)
    su = occ * rng.uniform(6, 11, T)
    sl = np.minimum(su, np.clip(occ * rng.uniform(-6, 3, T), -Crev, None))
    raw = rng.uniform(sl, su)
    sp = np.clip(raw, -Crev, C) if safe else raw * 1.2
    fb = np.where(sl > C, 1, -1)          # -1 = no fallback (SCHEMA_ADDITIONS.md)
    rows = []
    for rep in (0, 1):
        rows.append(pd.DataFrame(dict(exp_id=exp_id, method=exp_id.split("__")[0], test_cfg_id="workplace_N20_rho4", replay_id=rep, t=t,
                                      price_ch=price, price_dis=price, P_tr=Ptr, P_inf=Pinf, P_pv=Ppv, C=C, C_rev=Crev,
                                      sum_p=sp, sum_l=sl, sum_u=su, n_connected=occ.astype(int), fallback_code=fb)))
    df = pd.concat(rows, ignore_index=True)
    try:
        df.to_parquet(d / "steps.parquet", index=False)
    except ImportError:
        df.to_csv(d / "steps.csv", index=False)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True, help="output raw directory (must be inside synthetic_test/)")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--replay-scale", type=float, default=1.0)
    ap.add_argument("--small", action="store_true")
    a = ap.parse_args()
    if "synthetic_test" not in Path(a.out).resolve().parts:
        raise SystemExit("synthetic data may only be written inside a synthetic_test/ directory")
    print(generate(a.out, a.seed, a.replay_scale, small=a.small))
