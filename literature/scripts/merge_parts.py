#!/usr/bin/env python3
"""Merge literature sub-agent parts into the canonical literature files.

Inputs : parts/{L0,L1,L2,L3,S}_verified.jsonl, *_verified.bib, *_matrix.csv
Outputs: verified_refs.json, references.bib, paper_matrix.csv,
         style_corpus/style_corpus_refs.bib, merge_report.md
Rules:
 - dedupe by DOI (or arXiv id); first part in PART_ORDER wins the key;
 - matrix rows: prefer the row with read_level == full_text, then the longer row;
 - a matrix row without a verification record is dropped (and reported);
 - arXiv-only BibTeX year is set from the arXiv identifier (YYMM.xxxxx -> 20YY);
 - style-corpus-only references (part S) go to a separate bib file.
"""
import csv, json, re, sys, os, collections

PARTS = sys.argv[1] if len(sys.argv) > 1 else "parts"
OUT = sys.argv[2] if len(sys.argv) > 2 else "."
PART_ORDER = ["L0", "OR", "L1", "L2", "L3", "S"]
DROP_KEYS = {"orfanoudakis2024ev2gym"}  # duplicate record of orfanoudakis2025ev2gym (same DOI)

def ident(r):
    if r.get("doi"):
        return r["doi"].lower()
    return "arxiv:" + r["arxiv"].lower()

def split_bib(text):
    entries, depth, cur = [], 0, ""
    for ch in text:
        if depth == 0 and ch == "@":
            cur = "@"
            continue
        if cur:
            cur += ch
            if ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0:
                    entries.append(cur.strip())
                    cur = ""
    return entries

def bib_key(e):
    m = re.match(r"@\w+\{([^,]+),", e)
    return m.group(1).strip() if m else None

recs, bibs = collections.OrderedDict(), {}
key_alias = {}
for p in PART_ORDER:
    jf = os.path.join(PARTS, f"{p}_verified.jsonl")
    bf = os.path.join(PARTS, f"{p}_verified.bib")
    if not os.path.exists(jf):
        continue
    pbibs = {bib_key(e): e for e in split_bib(open(bf, encoding="utf-8").read())} if os.path.exists(bf) else {}
    for line in open(jf, encoding="utf-8"):
        r = json.loads(line)
        if r["key"] in DROP_KEYS:
            key_alias[r["key"]] = "orfanoudakis2025ev2gym"
            continue
        i = ident(r)
        if i in recs:
            key_alias[r["key"]] = recs[i]["key"]
            recs[i].setdefault("found_by_parts", []).append(p)
            continue
        r["found_by_parts"] = [p]
        r["style_corpus_only"] = (p == "S")
        recs[i] = r
        e = pbibs.get(r["key"])
        if e is None:
            print("WARNING no bib entry for", r["key"])
            continue
        if r.get("arxiv"):
            m = re.match(r"(\d{2})(\d{2})\.", r["arxiv"])
            if m:
                e = re.sub(r"year\s*=\s*\{\d{4}\}", "year = {20%s}" % m.group(1), e)
                r["year_bib"] = int("20" + m.group(1))
        bibs[r["key"]] = e

# part S records that are also cited elsewhere are not style-only
for r in recs.values():
    if r["style_corpus_only"] and any(x != "S" for x in r["found_by_parts"]):
        r["style_corpus_only"] = False

valid_keys = {r["key"] for r in recs.values()}
rows, dropped = {}, []
for p in PART_ORDER:
    mf = os.path.join(PARTS, f"{p}_matrix.csv")
    if not os.path.exists(mf):
        continue
    for row in csv.DictReader(open(mf, encoding="utf-8")):
        k = key_alias.get(row["id"], row["id"])
        row["id"] = k
        if k not in valid_keys:
            dropped.append((p, k))
            continue
        old = rows.get(k)
        score = (row.get("read_level") == "full_text", sum(len(v or "") for v in row.values()))
        if old is None or score > (old.get("read_level") == "full_text", sum(len(v or "") for v in old.values())):
            row["source_part"] = p
            rows[k] = row

os.makedirs(os.path.join(OUT, "style_corpus"), exist_ok=True)
json.dump(list(recs.values()), open(os.path.join(OUT, "verified_refs.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
with open(os.path.join(OUT, "references.bib"), "w", encoding="utf-8") as f:
    f.write("% Generated by merge_parts.py. Every entry has a record in verified_refs.json.\n\n")
    for r in recs.values():
        if not r["style_corpus_only"] and r["key"] in bibs:
            f.write(bibs[r["key"]] + "\n\n")
with open(os.path.join(OUT, "style_corpus", "style_corpus_refs.bib"), "w", encoding="utf-8") as f:
    for r in recs.values():
        if r["style_corpus_only"] and r["key"] in bibs:
            f.write(bibs[r["key"]] + "\n\n")
hdr = ["id","authors","year","venue","doi","problem","method","architecture","constraint_handling","guarantee_type","scalability","environment_or_data","baselines","key_results","limitations","relevance_to_us","read_level","evidence_source","source_part"]
with open(os.path.join(OUT, "paper_matrix.csv"), "w", encoding="utf-8", newline="") as f:
    w = csv.DictWriter(f, fieldnames=hdr, extrasaction="ignore")
    w.writeheader()
    for k in sorted(rows, key=lambda k: (-int(rows[k].get("relevance_to_us") or 0), k)):
        w.writerow(rows[k])

cited = [r for r in recs.values() if not r["style_corpus_only"]]
yr = lambda r: r.get("year_bib") or r.get("year") or 0
no_row = [r["key"] for r in cited if r["key"] not in rows]
with open(os.path.join(OUT, "merge_report.md"), "w", encoding="utf-8") as f:
    f.write("# Literature merge report\n\n")
    f.write(f"- Unique verified records: {len(recs)} (cited-candidate: {len(cited)}, style-corpus-only: {len(recs)-len(cited)})\n")
    f.write(f"- Cited-candidate references from 2022 or later: {sum(1 for r in cited if yr(r) >= 2022)}\n")
    f.write(f"- Matrix rows: {len(rows)} (full_text: {sum(1 for r in rows.values() if r.get('read_level')=='full_text')}, abstract_only: {sum(1 for r in rows.values() if r.get('read_level')!='full_text')})\n")
    f.write(f"- Key aliases applied (duplicates): {json.dumps(key_alias)}\n")
    f.write(f"- Matrix rows dropped for lack of verification: {dropped}\n")
    f.write(f"- Verified references without matrix row: {no_row}\n")
print(open(os.path.join(OUT, "merge_report.md")).read())
